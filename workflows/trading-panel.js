export const meta = {
  name: 'trading-panel',
  description: '复刻 TradingAgents 多智能体投研流程：四路分析师 → 多空辩论 → 研究经理裁决 → 交易方案 → 三方风控 → 组合经理拍板',
  whenToUse: '需要对一只股票或加密货币做多角度、可审查、留痕的研究时。args: {ticker, name, asOf, rounds, stance}',
  phases: [
    { title: '分析师取证', detail: '技术面/基本面/新闻面/情绪面 四路并发取证，不下买卖结论' },
    { title: '多空辩论', detail: '看多与看空研究员轮流交锋，轮数硬性封顶' },
    { title: '研究经理裁决', detail: '独立角色，逐条回应多空论点' },
    { title: '交易方案', detail: '把论点转成可执行方案' },
    { title: '风控审查', detail: '激进/保守并发挑刺，中性派抓自相矛盾' },
    { title: '组合经理拍板', detail: '最终评级、执行框架、数据盲区' },
  ],
}

// ---------- 输入 ----------
const ticker = (args && args.ticker) || 'AAPL'
const fullName = (args && args.name) || ticker
const asOf = (args && args.asOf) || '今天'
const ROUNDS = Math.min(Math.max((args && args.rounds) || 1, 1), 3)
const stance = (args && args.stance) || '纯研究（未持仓）'

const 共同纪律 = `
【硬性纪律】
- 用可联网查证的公开数据。查不到就写"无法获取"，绝对不许用记忆里的旧数字冒充当前行情。
- 每个数字必须带出处与日期。
- 本轮分析基准日：${asOf}。不要引用基准日之后才发生的信息。
- 中文输出，专业术语首次出现附英文。
`

// ---------- 结构化输出契约 ----------
const 报告SCHEMA = {
  type: 'object',
  required: ['要点', '正文', '数据盲区', '取证可信度'],
  properties: {
    要点: { type: 'array', items: { type: 'string' }, description: '3-6 条最关键的事实，每条带数字与日期' },
    正文: { type: 'string', description: '完整报告，Markdown' },
    数据盲区: { type: 'array', items: { type: 'string' }, description: '本次没能取到的关键数据，没有就写空数组' },
    取证可信度: { type: 'string', enum: ['高', '中', '低'] },
  },
}

const 论证SCHEMA = {
  type: 'object',
  required: ['核心主张', '论证', '引用的证据', '对对方的反驳'],
  properties: {
    核心主张: { type: 'string' },
    论证: { type: 'string' },
    引用的证据: { type: 'array', items: { type: 'string' } },
    对对方的反驳: { type: 'string', description: '第一轮可写"（首轮陈述）"' },
  },
}

const 裁决SCHEMA = {
  type: 'object',
  required: ['核心矛盾', '采纳与驳回', '决定性变量', '投资论点'],
  properties: {
    核心矛盾: { type: 'string' },
    采纳与驳回: { type: 'array', items: { type: 'string' }, description: '逐条回应多空各自的核心论点，写明采纳或驳回及理由' },
    决定性变量: { type: 'array', items: { type: 'string' }, description: '等什么明朗才能下更强的结论' },
    投资论点: { type: 'string' },
  },
}

const 方案SCHEMA = {
  type: 'object',
  required: ['方向', '理由摘要', '执行细节'],
  properties: {
    方向: { type: 'string', enum: ['买入', '增持', '持有', '减持', '卖出'] },
    理由摘要: { type: 'string' },
    执行细节: { type: 'string', description: '分批区间、仓位上限、止损位、时间维度' },
  },
}

const 风控SCHEMA = {
  type: 'object',
  required: ['立场', '对方案的质疑', '建议调整'],
  properties: {
    立场: { type: 'string' },
    对方案的质疑: { type: 'array', items: { type: 'string' } },
    建议调整: { type: 'string' },
    发现的自相矛盾: { type: 'array', items: { type: 'string' }, description: '仅中性派需要填，其余写空数组' },
  },
}

const 终裁SCHEMA = {
  type: 'object',
  required: ['评级', '摘要', '投资论点', '为何不更激进', '为何不更保守', '执行框架', '目标价', '时间维度', '决定性催化剂', '数据盲区'],
  properties: {
    评级: { type: 'string', enum: ['买入', '增持', '持有', '减持', '卖出'] },
    摘要: { type: 'string' },
    投资论点: { type: 'string' },
    为何不更激进: { type: 'string' },
    为何不更保守: { type: 'string' },
    执行框架: { type: 'string', description: '加仓触发条件 / 减仓防线 / 仓位上限' },
    目标价: { type: 'string' },
    时间维度: { type: 'string' },
    决定性催化剂: { type: 'array', items: { type: 'string' } },
    数据盲区: { type: 'array', items: { type: 'string' }, description: '本次分析缺了什么，结论因此在哪些方面不可靠' },
  },
}

// ---------- 第 1 阶段：四路分析师并发取证 ----------
phase('分析师取证')
log(`标的 ${ticker}（${fullName}）· 基准日 ${asOf} · 辩论 ${ROUNDS} 轮 · 视角：${stance}`)

const 分析师们 = [
  {
    key: '技术面',
    prompt: `你是技术面分析师，只负责取证与描述，禁止给出买卖建议。
研究标的：${ticker}（${fullName}）。
联网查证并报告：当前价与近期区间、50/200 日均线及其相对位置、成交量变化、MACD/RSI 等动量指标、
明确的支撑位与阻力位（给具体价位）、波动率（如 ATR）、以及相对大盘的表现。
${共同纪律}`,
  },
  {
    key: '基本面',
    prompt: `你是基本面分析师，只负责取证与描述，禁止给出买卖建议。
研究标的：${ticker}（${fullName}）。
联网查证并报告：最近几个季度的营收与同比环比、毛利率与其趋势、净利润与自由现金流、
现金与负债结构、订单积压或递延收入（若适用）、估值倍数（PE/PS/PB，注明是否前瞻）、
以及股本变化（增发、回购、稀释）。
${共同纪律}`,
  },
  {
    key: '新闻面',
    prompt: `你是新闻面分析师，只负责取证与描述，禁止给出买卖建议。
研究标的：${ticker}（${fullName}）。
联网查证并报告基准日之前 3 个月内的：重要公告与财报、重大合同或客户、并购与融资、
监管与法律事件、管理层变动、以及所属行业的关键事件。每条给日期与出处。
${共同纪律}`,
  },
  {
    key: '情绪面',
    prompt: `你是情绪面分析师，只负责取证与描述，禁止给出买卖建议。
研究标的：${ticker}（${fullName}）。
联网查证并报告：卖方分析师评级分布与目标价区间、近期评级调整、机构持仓与内部人交易变化、
散户社区（如 Reddit、StockTwits、雪球）的讨论热度与倾向、以及做空比例（short interest）。
取不到的项目必须明确写"无法获取"——情绪数据经常拿不到，谎报比缺失更有害。
${共同纪律}`,
  },
]

const 报告数组 = await parallel(
  分析师们.map((a) => () =>
    agent(a.prompt, { label: `分析:${a.key}`, phase: '分析师取证', schema: 报告SCHEMA })
      .then((r) => ({ key: a.key, ...r }))
  )
)

const 报告 = 报告数组.filter(Boolean)
const 盲区汇总 = 报告.flatMap((r) => (r.数据盲区 || []).map((b) => `[${r.key}] ${b}`))
log(`四路取证完成，收到 ${报告.length} 份报告；数据盲区 ${盲区汇总.length} 条`)

const 证据包 = 报告
  .map((r) => `### ${r.key}（可信度：${r.取证可信度}）\n要点：\n- ${(r.要点 || []).join('\n- ')}\n\n${r.正文}\n\n盲区：${(r.数据盲区 || []).join('；') || '无'}`)
  .join('\n\n---\n\n')

// ---------- 第 2 阶段：多空辩论（轮数硬封顶） ----------
phase('多空辩论')

const 辩论 = []
const 辩论记录文本 = () =>
  辩论.length === 0
    ? '（尚无发言）'
    : 辩论.map((d) => `【${d.方}·第${d.轮}轮】主张：${d.核心主张}\n${d.论证}\n反驳：${d.对对方的反驳}`).join('\n\n')

for (let r = 1; r <= ROUNDS; r++) {
  const 看多 = await agent(
    `你是看多研究员（Bull Researcher）。你的职责是论证 ${ticker}（${fullName}）是一个机会。
必须引用下列证据中的具体数字，禁止空泛看好。若证据不足以支撑某个主张，明说"此处缺证据"。

# 证据包
${证据包}

# 迄今辩论记录
${辩论记录文本()}

这是第 ${r} 轮（共 ${ROUNDS} 轮）。若已有看空发言，必须逐条反驳其最强论点。
${共同纪律}`,
    { label: `看多·第${r}轮`, phase: '多空辩论', schema: 论证SCHEMA }
  )
  if (看多) 辩论.push({ 方: '看多', 轮: r, ...看多 })

  const 看空 = await agent(
    `你是看空研究员（Bear Researcher）。你的职责是论证这笔投资最可能怎么亏钱。
要求具体到"什么条件触发、代价多大"，禁止"可能存在风险"这类无信息量的话。
你的价值在于找出别人不愿看的东西——估值透支、现金流缺口、假设不成立、竞争格局恶化、稀释、监管。

# 证据包
${证据包}

# 迄今辩论记录
${辩论记录文本()}

这是第 ${r} 轮（共 ${ROUNDS} 轮）。必须逐条反驳看多方本轮的最强论点。
${共同纪律}`,
    { label: `看空·第${r}轮`, phase: '多空辩论', schema: 论证SCHEMA }
  )
  if (看空) 辩论.push({ 方: '看空', 轮: r, ...看空 })

  log(`第 ${r} 轮辩论完成`)
}

// ---------- 第 3 阶段：研究经理裁决（独立角色） ----------
phase('研究经理裁决')

const 裁决 = await agent(
  `你是研究经理（Research Manager）。你没有参与刚才的辩论，只看证据与双方论证。
你的任务不是选边站，而是判断哪些论点站得住、哪些站不住，并指出当前的核心矛盾。

要求：
1. 逐条回应多空双方的核心主张，写明采纳还是驳回、理由是什么。不许绕过任何一方的最强论点。
2. 主动指出双方论证中的自相矛盾或逻辑漏洞。
3. 明确"决定性变量"：等什么明朗之后才能下更强的结论。

# 证据包
${证据包}

# 辩论全文
${辩论记录文本()}
${共同纪律}`,
  { label: '研究经理', phase: '研究经理裁决', schema: 裁决SCHEMA }
)

// ---------- 第 4 阶段：交易员出方案 ----------
phase('交易方案')

const 方案 = await agent(
  `你是交易员（Trader）。基于研究经理的投资论点，给出一个可执行方案。
当前持仓视角：${stance}。

必须包含：方向、理由摘要（三句以内）、以及执行细节——分批区间、单次与总仓位上限、
止损位（说明依据，如 ATR 倍数或斐波那契回撤位）、时间维度。
方案要能被风控挑刺，所以参数必须具体到数字。

# 投资论点
${裁决 ? 裁决.投资论点 : '（研究经理未产出，请基于证据包自行判断并说明）'}

# 核心矛盾
${裁决 ? 裁决.核心矛盾 : '无'}

# 决定性变量
${裁决 ? (裁决.决定性变量 || []).join('；') : '无'}

# 证据包
${证据包}
${共同纪律}`,
  { label: '交易员', phase: '交易方案', schema: 方案SCHEMA }
)

const 方案文本 = 方案
  ? `方向：${方案.方向}\n理由：${方案.理由摘要}\n执行细节：${方案.执行细节}`
  : '（交易员未产出方案）'

// ---------- 第 5 阶段：风控审查（激进与保守并发，中性派收口） ----------
phase('风控审查')

const 两派 = await parallel([
  () =>
    agent(
      `你是激进派风控分析师（Aggressive Risk Analyst）。你从机会成本视角审视交易方案：
过于保守会错过什么？止损是否设得太紧以至于会被正常波动误伤？仓位是否小到即使判断正确也赚不到钱？

# 待审方案
${方案文本}

# 证据包
${证据包}
${共同纪律}`,
      { label: '风控·激进', phase: '风控审查', schema: 风控SCHEMA }
    ),
  () =>
    agent(
      `你是保守派风控分析师（Conservative Risk Analyst）。你从下行保护视角审视交易方案：
最坏情况有多坏？防线够不够？流动性、波动率、宏观环境是否被低估？黑天鹅在哪？

# 待审方案
${方案文本}

# 证据包
${证据包}
${共同纪律}`,
      { label: '风控·保守', phase: '风控审查', schema: 风控SCHEMA }
    ),
])

const 激进 = 两派[0]
const 保守 = 两派[1]
const 派别文本 = (p, 名) =>
  p ? `【${名}】立场：${p.立场}\n质疑：\n- ${(p.对方案的质疑 || []).join('\n- ')}\n建议：${p.建议调整}` : `【${名}】（未产出）`

const 中性 = await agent(
  `你是中性派风控分析师（Neutral Risk Analyst）。你的首要职责不是折中，而是
**找出激进派与保守派各自论证中的自相矛盾、以及彼此打架却都没意识到的地方**。
典型例子：一边反对宽止损、一边又要求把止损设在距现价极近处——在高波动标的上这几乎必然误伤。
找到这类矛盾并明确指出，是你最大的价值。然后给出一个两边都无法反驳的可执行折中方案。

# 待审方案
${方案文本}

${派别文本(激进, '激进派')}

${派别文本(保守, '保守派')}

# 证据包
${证据包}
${共同纪律}`,
  { label: '风控·中性', phase: '风控审查', schema: 风控SCHEMA }
)

// ---------- 第 6 阶段：组合经理拍板 ----------
phase('组合经理拍板')

const 终裁 = await agent(
  `你是投资组合经理（Portfolio Manager），本次流程的最终裁决者，未参与前面任何辩论。
你要在充分吸收所有分歧之后给出结论，并对结论负责。

要求：
1. 逐条回应多空双方与三派风控的核心主张，写明为何采纳或驳回。
2. 必须分别写明"为何不更激进"与"为何不更保守"——两边都要有交代。
3. 执行框架必须具体到可观测的数字与条件。
4. 数据盲区必须如实汇总，并说明结论因此在哪些方面不可靠。若情绪面或宏观数据缺失，
   必须明确指出结论主要建立在哪几路证据上。

# 证据包
${证据包}

# 多空辩论
${辩论记录文本()}

# 研究经理裁决
${裁决 ? `核心矛盾：${裁决.核心矛盾}\n采纳与驳回：\n- ${(裁决.采纳与驳回 || []).join('\n- ')}\n投资论点：${裁决.投资论点}` : '（无）'}

# 交易方案
${方案文本}

# 风控三方
${派别文本(激进, '激进派')}

${派别文本(保守, '保守派')}

${派别文本(中性, '中性派')}
中性派发现的自相矛盾：${中性 ? (中性.发现的自相矛盾 || []).join('；') || '无' : '无'}

# 已知数据盲区
${盲区汇总.join('；') || '无'}
${共同纪律}`,
  { label: '组合经理', phase: '组合经理拍板', schema: 终裁SCHEMA }
)

log(`裁决完成：${终裁 ? 终裁.评级 : '未产出'}`)

return {
  标的: ticker,
  全称: fullName,
  基准日: asOf,
  辩论轮数: ROUNDS,
  持仓视角: stance,
  分析师报告: 报告,
  多空辩论: 辩论,
  研究经理裁决: 裁决,
  交易方案: 方案,
  风控: { 激进, 保守, 中性 },
  最终裁决: 终裁,
  数据盲区汇总: 盲区汇总,
}
